"""Prediction record — model output for one query, scored against the hierarchy."""

from __future__ import annotations

from typing import Any

from pydantic import BaseModel, Field


class PredictionRecord(BaseModel):
    """The result of running one query against a model checkpoint."""

    experiment_id: str
    checkpoint_id: str = Field(description="Model state identifier (e.g. MF, MG, MU_B2)")
    query_id: str

    raw_output: str = Field(description="Full raw text generated by the model")
    parsed_answer: str | None = Field(
        default=None,
        description="Deterministically or LLM-judged canonical answer string",
    )
    matched_canonical_id: str | None = Field(
        default=None,
        description="canonical_id of the hierarchy node the answer matched",
    )
    predicted_level: int | None = Field(
        default=None,
        description="Hierarchy level of the matched node (None if unresolved)",
    )

    # Hierarchy-relative correctness flags
    is_correct_branch: bool | None = Field(
        default=None,
        description="True if the answer is on the correct branch of the hierarchy",
    )
    is_finer_than_target: bool | None = Field(
        default=None,
        description="True if the answer reveals information finer than the target level",
    )
    is_coarser_than_target: bool | None = Field(
        default=None,
        description="True if the answer is less specific than the target level",
    )

    metadata: dict[str, Any] = Field(
        default_factory=dict,
        description="Extra info: generation time, token count, judge confidence, etc.",
    )
