def verify_freeze(repo_root: Path, path: Path | None = None) -> list[str]:
    """Recompute the freeze against the repository. Empty list == matches.

    The prediction block is excluded here and verified by
    :func:`verify_predictions`, because those files are gitignored and their
    absence in a clone is not a mismatch.
    """
    path = path or repo_root / OUT_REPORT
    if not path.exists():
        return [f"{path} does not exist -- the basis is not frozen"]
    old = _flat(json.loads(path.read_text()))
    fresh = _flat(build_freeze(repo_root))
    skip = VOLATILE_FIELDS + CLONE_DEPENDENT_FIELDS
    reasons = []
    for key in sorted(set(old) | set(fresh)):
        if any(key.startswith(f"{v}.") or key == v for v in skip):
            continue
        if old.get(key) != fresh.get(key):
            reasons.append(f"{key}: frozen={old.get(key)!r} "
                           f"now={fresh.get(key)!r}")
    return reasons


def verify_predictions(repo_root: Path,
                       path: Path | None = None) -> dict[str, list[str]]:
    """Three-valued check of the prediction bytes the re-scoring reads."""
    path = path or repo_root / OUT_REPORT
    doc = json.loads(path.read_text())
    block = doc[PREDICTIONS_FIELD]
    frozen: dict[str, str] = block["sha256"]
    paths: dict[str, str] = block["paths"]
    out = {"match": [], "mismatch": [], "absent": []}
    for key, rel in sorted(paths.items()):
        p = repo_root / rel
        if key not in frozen:
            out["absent"].append(f"{key}: not present when the basis was frozen")
        elif not p.exists():
            out["absent"].append(f"{key}: {rel} is absent from this clone")
        elif _sha256(p) != frozen[key]:
            out["mismatch"].append(
                f"{key}: frozen={frozen[key][:16]} now={_sha256(p)[:16]}")
        else:
            out["match"].append(key)
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--check-only", action="store_true",
                    help="Verify the committed freeze instead of writing it")
    ap.add_argument("--refreeze", action="store_true",
                    help="Amend an existing freeze, recording the amendment. "
                         "Refused once the re-scoring has been filed.")
    ap.add_argument("--reason", default=None,
                    help="Why the freeze is being amended (with --refreeze)")
    ap.add_argument("--repo-root", default=None)
    args = ap.parse_args()
    repo_root = Path(args.repo_root) if args.repo_root \
        else (_find_repo_root(Path.cwd()) or Path.cwd())
    out = repo_root / OUT_REPORT

    if args.check_only:
        reasons = verify_freeze(repo_root)
        preds = verify_predictions(repo_root) if out.exists() else {
            "match": [], "mismatch": [], "absent": []}
        contract = verify_contract(repo_root) if out.exists() else {
            "contract_conflicts": [], "missing_sidecars": [],
            "distinct_contracts": 0, "num_with_a_sidecar": 0}
        #: A contract conflict is fatal anywhere; missing sidecars are only
        #: fatal for a run that has to read those parquets, and --check-only
        #: does not.
        if reasons or preds["mismatch"] or contract["contract_conflicts"]:
            if reasons:
                print("MISMATCHES:")
                for r in reasons:
                    print(f"  {r}")
            for m in preds["mismatch"]:
                print(f"  PREDICTION {m}")
            for c in contract["contract_conflicts"]:
                print(f"  CONTRACT {c}")
            raise SystemExit(1)
        print(f"OK — the Stage-1c route-stratification freeze still matches "
              f"the repository (volatile fields excluded: "
              f"{list(VOLATILE_FIELDS)}; clone-dependent fields verified "
              f"separately: {list(CLONE_DEPENDENT_FIELDS)})")
        print(f"  predictions bound: {len(preds['match'])} match, "
              f"{len(preds['absent'])} absent from this clone")
        for a in preds["absent"]:
            print(f"    absent: {a}")
        print(f"  measurement contracts: {contract['distinct_contracts']} "
              f"distinct over {contract['num_with_a_sidecar']} sidecar(s); "
              f"{len(contract['missing_sidecars'])} parquet(s) without one")
        return

    #: Evaluated FIRST and unconditionally: no flag, including --refreeze,
    #: reaches past it.  This study trains nothing, so the thing that must not
    #: postdate the rule is the SCORE.
    if scored(repo_root):
        raise SystemExit(
            f"REFUSING to freeze: {ANALYSIS_REPORT} already exists. A basis "
            f"written now would postdate the scores it is supposed to govern, "
            f"and could be fitted to them -- which route to read, whether to "
            f"pool or stratify, and how wide the probe is, are all choices "
            f"whose answer changes once the numbers are visible.")

    document = build_freeze(repo_root)
    if out.exists():
        previous = json.loads(out.read_text())
        if not args.refreeze:
            raise SystemExit(
                f"REFUSING to overwrite {out} (sha256 {_sha256(out)}). It is "
                f"the record that this basis predates its own scoring; "
                f"deleting or replacing it is the one act that would make that "
                f"claim unfalsifiable. --refreeze --reason amends it with the "
                f"change recorded.")
        if not args.reason:
            raise SystemExit("--refreeze requires --reason: an amendment whose "
                             "reason is not written down is indistinguishable "
                             "from a quiet rewrite.")
        old_flat, new_flat = _flat(previous), _flat(document)
        skip = VOLATILE_FIELDS + CLONE_DEPENDENT_FIELDS
        changed = sorted(
            k for k in set(old_flat) | set(new_flat)
            if not any(k.startswith(f"{v}.") or k == v for v in skip)
            and old_flat.get(k) != new_flat.get(k))
        document["amendments"] = [*previous.get("amendments", []), {
            "utc": document["frozen_at_utc"],
            "reason": args.reason,
            "supersedes_sha256": _sha256(out),
            "fields_that_changed": changed,
            "no_score_had_been_filed": True,
        }]
        #: An amendment may rebind the predictions but must keep the ones the
        #: previous freeze recorded, so a byte that was scored cannot be
        #: swapped silently.
        document[PREDICTIONS_FIELD]["sha256"] = {
            **document[PREDICTIONS_FIELD]["sha256"],
            **{k: v for k, v in previous[PREDICTIONS_FIELD]["sha256"].items()},
        }
