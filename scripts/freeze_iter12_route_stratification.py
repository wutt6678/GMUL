"""Freeze the route-stratified retention floor before anything is scored on it.

Stage 1c extends the frozen four-number retention floor to eight by reading the
image-route retention families beside the text-route ones.  This script
hash-binds that decision so the rule cannot be edited between being written down
and being applied.

WHY A FREEZE IS NEEDED FOR A RE-SCORING THAT TRAINS NOTHING
-----------------------------------------------------------
Stage 1c spends no GPU: every prediction it reads was already generated by Stage
1 and Stage 1b.  That makes the usual protection -- "the protocol predates the
training" -- unavailable, because the training has already happened.  What is
still protectable is the order between the RULE and the SCORE.  A basis written
after seeing the stratified numbers could be fitted to them: drop the image
route if it is inconvenient, keep it if it is not, pool instead of stratify, or
narrow the probe.  So the refusal here is keyed on the ANALYSIS REPORT rather
than on adapters, and it is evaluated before any flag is considered.

WHAT IS BOUND
-------------
Four protocol paths (this file, the metric module, the basis builder, the
analyzer), the modules they import whose behaviour is part of the measurement,
the committed reports the basis is derived from, the dataset parquets, and --
separately, because they are gitignored and absent from a clone -- the sha256 of
every prediction parquet the re-scoring will read.  Binding those bytes is what
makes "re-scored from existing predictions" a checkable claim rather than a
description.

The prediction block is verified apart from the rest and reports three outcomes
per path -- match, mismatch, absent -- rather than folding absence into a pass.
A clone without predictions therefore says so explicitly instead of silently
verifying fewer things.

Nothing here reads the sealed confirmation split and nothing edits a frozen
path.  ``retention_selection``, ``hierarchy_metrics``, ``candidate_grid`` and
``seed_replication`` are imported and called; the two prior freezes are read and
re-verified, not rewritten.
"""

