#: Verified separately; see the module docstring for why absence is reported
#: rather than passed over.
PREDICTIONS_FIELD = "predictions_bound"
CONTRACT_FIELD = "measurement_contract"

#: Fields whose value depends on gitignored prediction parquets being present.
#: Excluded from the flat document comparison and checked by their own
#: three-valued verifiers instead, so that a clone -- which legitimately has
#: none of those bytes -- reports "fewer things to check" rather than either a
#: false mismatch or a silent pass over a shorter list.
CLONE_DEPENDENT_FIELDS = (PREDICTIONS_FIELD, CONTRACT_FIELD)

#: The splits the re-scoring reads, and the parquet naming convention that goes
#: with them.  Same scope as the frozen basis: the test split stays out.
SPLITS = ("train", "val")

#: Sidecar keys that must be IDENTICAL across every bound parquet.  This is not
#: bookkeeping: the image route is the one whose correctness flips when batch
#: composition changes -- measured at 15 flips out of 4,518 rows between two B0
#: parquets generated from identical adapter bytes at image_batch_size 8 and 1,
#: and every one of the 15 was image-route.  Stage 1c compares image-route
#: numbers ACROSS two prediction directories (the seed-42 replicates are read
#: from Stage 1's), so a contract difference between them would put the headline
#: comparison on two different instruments.  The frozen text-route floor never
#: needed this check because all 484 of its queries are text_to_text; the image
#: stratum does.
CONTRACT_MUST_MATCH = ("batch_size", "image_batch_size", "max_new_tokens",
                       "max_length", "max_image_pixels", "do_sample")
#: Bound beside the generation config, because a contract is not only decoding.
SIDECAR_MUST_MATCH = ("base_model_revision", "contract_version")
DATASET_MUST_MATCH = ("version",)


def sidecar_for(repo_root: Path, parquet_rel: str) -> Path:
    """The provenance sidecar that belongs to one bound parquet."""
    return repo_root / (parquet_rel + ".provenance.json")


def contract_signature(doc: dict[str, Any]) -> dict[str, Any]:
    """The part of a sidecar that decides what instrument produced a parquet."""
    gc = doc.get("generation_config") or {}
    ds = doc.get("dataset") or {}
    return {
        **{k: gc.get(k) for k in CONTRACT_MUST_MATCH},
        **{k: doc.get(k) for k in SIDECAR_MUST_MATCH},
        **{f"dataset.{k}": ds.get(k) for k in DATASET_MUST_MATCH},
    }


def verify_contract(repo_root: Path) -> dict[str, Any]:
    """Are all bound parquets one instrument?  Empty ``problems`` == yes.

    Reported three ways rather than as a boolean: which signatures were seen,
    how many parquets carry each, and which paths are missing a sidecar.  A
    parquet whose sidecar is absent cannot be certified as the same instrument,
    and that is a problem rather than a pass.
    """
    paths = prediction_paths(repo_root)
    sigs: dict[str, dict] = {}
    missing: list[str] = []
    for key, rel in sorted(paths.items()):
        sc = sidecar_for(repo_root, rel)
        if not sc.exists():
            missing.append(f"{key}: {sc.name} is absent")
            continue
        sigs[key] = contract_signature(json.loads(sc.read_text()))
    distinct: dict[str, list[str]] = {}
    for key, sig in sigs.items():
        distinct.setdefault(json.dumps(sig, sort_keys=True), []).append(key)
    #: Kept apart from missing sidecars, because the two have different
    #: consequences.  A conflict between present parquets means the comparison
    #: spans two instruments and is invalid anywhere.  A missing sidecar means
    #: this clone cannot certify that parquet -- which is a fact about the
    #: clone, and is fatal only for a run that needs to read it.
    conflicts = []
    if len(distinct) > 1:
        conflicts.append(
            f"{len(distinct)} distinct measurement contracts across the bound "
            f"parquets: " + " | ".join(
                f"{len(v)} x {k[:120]}" for k, v in sorted(distinct.items())))
    return {
        "num_bound_parquets": len(paths),
        "num_with_a_sidecar": len(sigs),
        "distinct_contracts": len(distinct),
        "contract": json.loads(next(iter(distinct))) if len(distinct) == 1
        else None,
        "keys_compared": sorted({k for sig in sigs.values() for k in sig}),
        "missing_sidecars": missing,
        "contract_conflicts": conflicts,
        "problems": missing + conflicts,
        "one_instrument": not (missing or conflicts),
    }


def prediction_filename(state_id: str) -> str:
    """The train+val parquet name, built the way the Stage-1b analyzer builds it."""
    return f"predictions_{''.join(s[0] for s in SPLITS)}_{state_id}.parquet"


def stage1_states() -> list[str]:
    """MG plus every Stage-1 grid row, derived from the frozen grid.

    Read out of ``iter12_grid`` rather than written down here, so the state list
    cannot drift from the grid the candidates were trained from.
    """
    return ["MG", *(spec.candidate_id for spec in iter12_grid())]


def stage1b_states(repo_root: Path) -> list[tuple[str, str]]:
    """(replicate_id, repo-relative parquet) for all eight replicates.

    The seed-42 replicate was reused from Stage 1, so its predictions live in
    the Stage-1 directory; the six trained replicates live in the Stage-1b one.
    Resolving that here, once, against ``repo_root`` and returning paths
    RELATIVE to it, is what stops the two directories being confused later.
    Joining a resolver's output onto ``repo_root`` a second time is the same
    double-prefix class of bug that killed the Stage-1b control in two seconds.
    """
    stage1 = stage1_predictions_dir(repo_root)
    seeds = seed_predictions_dir(repo_root)
    out: list[tuple[str, str]] = []
    for r in replicates():
        where = stage1 if r.reused else seeds
        name = prediction_filename(r.parent if r.reused else r.replicate_id)
        out.append((r.replicate_id, str((where / name).relative_to(repo_root))))
    return out


def prediction_paths(repo_root: Path) -> dict[str, str]:
    """Every parquet the re-scoring will read, as a repo-relative path.

    Stage 1b's B0 is included even though Stage 1 also has one: the Stage-1b
    control regenerated it, and the re-scoring anchors on the Stage-1 B0, so
    both are bound and the analyzer says which it used.
    """
    stage1 = stage1_predictions_dir(repo_root)
    seeds = seed_predictions_dir(repo_root)
    out: dict[str, str] = {}
    for state in stage1_states():
        out[f"stage1.{state}"] = str(
            (stage1 / prediction_filename(state)).relative_to(repo_root))
    for rid, rel in stage1b_states(repo_root):
        out[f"stage1b.{rid}"] = rel
    out["stage1b.B0"] = str(
        (seeds / prediction_filename("B0")).relative_to(repo_root))
    for key, rel in out.items():
        if rel.startswith("data/data/") or not rel.startswith("data/"):
            raise SystemExit(
                f"{key} resolved to {rel!r}, which is not a repo-relative "
                f"prediction path; the resolvers and this script disagree "
                f"about who supplies the data/ prefix")
    return out


def scored(repo_root: Path) -> bool:
    """Whether the stratified re-scoring has already been filed."""
    return (repo_root / ANALYSIS_REPORT).exists()


